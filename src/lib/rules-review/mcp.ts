interface RuleRow {
  cardId: string;
  name: string;
  setCode: string;
  side: string;
  skillIndex: number;
  kind: string;
  printed: string;
  reads: string;
  status: string;
  source: string;
  unread: string[];
  explanation: string | null;
  confirmedAt: Date | null;
}

const cols = {
  cardId: cardRules.cardId,
  name: cards.name,
  setCode: cards.setCode,
  side: cardRules.side,
  skillIndex: cardRules.skillIndex,
  kind: cardRules.kind,
  printed: cardRules.printed,
  reads: cardRules.reads,
  status: cardRules.status,
  source: cardRules.source,
  unread: cardRules.unread,
  explanation: cardRules.explanation,
  confirmedAt: cardRules.confirmedAt,
};

const keyOf = (r: RuleRow) => `${r.cardId}${r.side === "back" ? "b" : ""}#${r.skillIndex}`;
const num = (v: unknown, def: number, max: number) => Math.min(Math.max(Number.isFinite(Number(v)) ? Math.trunc(Number(v)) : def, 0), max);

async function openRows(db: Db, where: { set?: string; idPrefix?: string }): Promise<RuleRow[]> {
  const conds = [sql`jsonb_array_length(${cardRules.unread}) > 0`];
  if (where.set) conds.push(eq(cards.setCode, where.set));
  if (where.idPrefix) conds.push(ilike(cardRules.cardId, `${where.idPrefix.replace(/[%_\\]/g, "\\$&")}%`));
  return (await db
    .select(cols)
    .from(cardRules)
    .innerJoin(cards, eq(cards.id, cardRules.cardId))
    .where(and(...conds))
    .orderBy(asc(cardRules.cardId), asc(cardRules.side), asc(cardRules.skillIndex))) as RuleRow[];
}

const ruleOut = (r: RuleRow) => ({
  key: keyOf(r),
  side: r.side,
  name: r.name,
  set: r.setCode,
  kind: r.kind,
  printed: r.printed,
  reading: r.reads || "(nothing)",
  status: r.status,
  unread: r.unread.map(flat),
});

async function callTool(name: string, args: Record<string, unknown>, deps: McpDeps): Promise<unknown> {
  const { db, env } = deps;
  switch (name) {
    case "list_open_families": {
      const all = await openRows(db, {});
      const fam = new Map<string, RuleRow[]>();
      for (const r of all) {
        const k = familyOf(r.unread[0] ?? "");
        (fam.get(k) ?? fam.set(k, []).get(k)!).push(r);
      }
      const out = [...fam.entries()]
        .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
        .slice(0, num(args.limit, 40, 500))
        .map(([family, rs]) => ({ family, count: rs.length, examples: rs.slice(0, 3).map((r) => ({ key: keyOf(r), unread: truncate(r.unread[0] ?? "", 200) })) }));
      return { openSkills: all.length, families: fam.size, top: out };
    }
    case "list_open_rules": {
      const all = await openRows(db, { set: typeof args.set === "string" ? args.set : undefined, idPrefix: typeof args.idPrefix === "string" ? args.idPrefix : undefined });
      const f = typeof args.family === "string" ? args.family.toLowerCase() : "";
      const hit = f ? all.filter((r) => familyOf(r.unread[0] ?? "").includes(f)) : all;
      const offset = num(args.offset, 0, 100000);
      const limit = num(args.limit, 20, 100);
      return { total: hit.length, offset, rules: hit.slice(offset, offset + limit).map(ruleOut) };
    }
    case "get_card": {
      const id = String(args.cardId ?? "").trim();
      if (!id) throw new Error("cardId is required");
      const rs = (await db
        .select(cols)
        .from(cardRules)
        .innerJoin(cards, eq(cards.id, cardRules.cardId))
        .where(sql`upper(${cardRules.cardId}) = ${id.toUpperCase().replace(/(-\d+)B$/, "$1")}`)
        .orderBy(asc(cardRules.side), asc(cardRules.skillIndex))) as RuleRow[];
      return {
        cardId: id,
        skills: rs.map((r) => ({ ...ruleOut(r), source: r.source, confirmed: r.status === "confirmed" || r.status === "corrected" || r.confirmedAt != null, explanation: r.explanation })),
      };
    }
    case "list_assumptions": {
      const id = typeof args.cardId === "string" ? args.cardId.toUpperCase() : "";
      const all = (assumptionsData as { id: number; cards: string[] }[]).filter((a) => !id || a.cards.some((c) => c.toUpperCase() === id));
      const offset = num(args.offset, 0, 1000);
      return { total: all.length, offset, assumptions: all.slice(offset, offset + num(args.limit, 50, 100)) };
    }
    case "record_ruling": {
      const token = env.GITHUB_ISSUES_TOKEN;
      if (!token) throw new Error("GITHUB_ISSUES_TOKEN is not configured; give the owner the issue text to paste instead");
      const ids = Array.isArray(args.cardIds) ? args.cardIds.map((x) => flat(String(x))).filter(Boolean) : [];
      const title = flat(String(args.title ?? ""));
      const decision = String(args.decision ?? "").trim();
      if (!ids.length || !title || !decision) throw new Error("cardIds, title and decision are required");
      const heading = `Ruling: ${ids.slice(0, 3).join(", ")}${ids.length > 3 ? ` +${ids.length - 3}` : ""} — ${title}`.slice(0, 200);
      const body = [
        `**Affected card ids:** ${ids.join(", ")}`,
        "",
        "**Owner's decision (verbatim):**",
        "",
        decision
          .split("\n")
          .map((l) => `> ${l}`)
          .join("\n"),
        ...(args.notes ? ["", "**Notes:**", "", String(args.notes)] : []),
        "",
        "Status: decided — to be stored with `npm run arena:rule` and implemented",
        "",
        "_Recorded from the claude.ai rules-review connector._",
      ].join("\n");
      const issue = await createIssue(token, heading, body, deps.fetch);
      return { issueNumber: issue.number, url: issue.url };
    }
    case "deck_review_queue":
      return deckReviewQueue(deps, args);
    case "get_card_review":
      return getCardReview(deps, args);
    case "confirm_rule":
      return confirmRule(deps, args);
    case "flag_rule":
      return flagRule(deps, args);
    case "comment_ruling": {
      const token = env.GITHUB_ISSUES_TOKEN;
      if (!token) throw new Error("GITHUB_ISSUES_TOKEN is not configured");
      const n = Number(args.issueNumber);
      const text = String(args.text ?? "").trim();
      if (!Number.isInteger(n) || n <= 0 || !text) throw new Error("issueNumber and text are required");
      return await commentOnIssue(token, n, text, deps.fetch);
    }
    default:
      throw new Error(`unknown tool ${name}`);
  }
}

type Rpc = { jsonrpc?: string; id?: string | number | null; method?: string; params?: Record<string, unknown> };

async function handleOne(msg: Rpc, deps: McpDeps): Promise<Record<string, unknown> | null> {
  const isNotification = msg.id === undefined || msg.id === null;
  const reply = (result: unknown) => ({ jsonrpc: "2.0", id: msg.id ?? null, result });
  const error = (code: number, message: string) => ({ jsonrpc: "2.0", id: msg.id ?? null, error: { code, message } });
  switch (msg.method) {
    case "initialize": {
      const asked = msg.params?.protocolVersion;
      return reply({
        protocolVersion: typeof asked === "string" ? asked : "2025-03-26",
        capabilities: { tools: {} },
        serverInfo: { name: "dbs-rules-review", version: "1.0.0" },
      });
    }
    case "ping":
      return reply({});
    case "tools/list":
      return reply({ tools: allowedTools(deps.scopes) });
    case "tools/call": {
      const name = String(msg.params?.name ?? "");
      if (!allowedTools(deps.scopes).some((t) => t.name === name)) return error(-32602, `unknown tool, or its scope was not granted: ${name}`);
      try {
        const out = await callTool(name, (msg.params?.arguments as Record<string, unknown>) ?? {}, deps);
        return reply({ content: [{ type: "text", text: JSON.stringify(out, null, 1) }] });
      } catch (e) {
        // The message is ours (no secrets in it); a driver error is reduced to its class.
        const text = e instanceof Error && !/postgres|connect|select |insert /i.test(e.message) ? e.message : "the tool failed";
        return reply({ isError: true, content: [{ type: "text", text }] });
      }
    }
    default:
      if (isNotification) return null;
      return error(-32601, `method not found: ${msg.method}`);
  }
}

/** The POST body of one MCP request (a message or a batch) -> the HTTP response. */
export async function handleMcpPost(req: Request, deps: McpDeps): Promise<Response> {
  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return Response.json({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "parse error" } }, { status: 400 });
  }
  const batch = Array.isArray(body);
  const out: Record<string, unknown>[] = [];
  for (const m of (batch ? body : [body]) as unknown[]) {
    const r = await handleOne((m ?? {}) as Rpc, deps);
    if (r) out.push(r);
  }
  if (!out.length) return new Response(null, { status: 202 });
  return Response.json(batch ? out : out[0]);
}
