/**
 * A minimal MCP server (Streamable HTTP, stateless, JSON-RPC by hand — no SDK
 * dependency) for reviewing the arena's open rules from claude.ai.
 *
 * Reads this app's `card_rules` / `cards` / decks. Writes: GitHub issues labelled
 * `rule-assumption` (and comments on them), and two narrow `card_rules` writes in
 * `deck-review.ts`: `confirm_rule` (a fully read compiler draft -> confirmed, program
 * untouched) and `flag_rule` (a suspected-misread note). It never changes a program or
 * touches a row a person already confirmed: a ruling is stored with `npm run arena:rule`.
 *
 * The route (`src/app/api/mcp/route.ts`) has verified the OAuth bearer token
 * (`src/lib/oauth/store.ts`) and passes its scopes; this module takes the
 * database, env, scopes and fetch as arguments so a test can run it on PGlite
 * with GitHub mocked.
 */
import { and, asc, eq, ilike, sql } from "drizzle-orm";
import type { Db } from "@/db";
import { cardRules, cards } from "@/db/schema";
import assumptionsData from "./assumptions.generated.json";
import { confirmRule, deckReviewQueue, flagRule, getCardReview } from "./deck-review";
import { commentOnIssue, createIssue, LABEL, REPO } from "./github";
import { familyOf, flat, truncate } from "./wording";

export interface McpDeps {
  db: Db;
  env: Record<string, string | undefined>;
  /** The OAuth scopes of the verified token (`rules-read`, `rules-write`). */
  scopes: readonly string[];
  /** The verified token's SL address: deck scope and the "who" of a confirmation. */
  email?: string;
  fetch?: typeof fetch;
}

const WRITE_TOOLS = new Set(["record_ruling", "comment_ruling", "confirm_rule", "flag_rule"]);

/** The tools a token's scopes allow: all read-only tools for `rules-read`, the writes for `rules-write`. */
const allowedTools = (scopes: readonly string[]) => TOOLS.filter((t) => scopes.includes(WRITE_TOOLS.has(t.name) ? "rules-write" : "rules-read"));

const str = { type: "string" } as const;
const int = { type: "integer" } as const;

