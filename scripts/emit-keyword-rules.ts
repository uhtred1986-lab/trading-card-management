/**
 * Writes `src/lib/arena/keyword-rules.generated.ts`: what each keyword skill does, for the ⓘ beside a keyword
 * on a card (owner, 19 Oct 2026). The glossary's `meaning` line and the Rule Manual's own section
 * (`docs/rules/rulemanual.txt`, chapter 22), cut down to what a card review needs. The glossary itself is
 * too large to ship to the browser, hence a generated copy; `scripts/verify/keyword-rules.ts` (part of
 * `npm test`) fails when the copy is stale.
 *
 *   npx tsx scripts/emit-keyword-rules.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { KEYWORDS } from "../src/lib/arena/glossary";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const KEYWORD_RULES_FILE = join(ROOT, "src/lib/arena/keyword-rules.generated.ts");

/** The paragraphs of one chapter-22 section, page numbers and wrapping removed. */
function manualSection(lines: string[], section: string): { id: string; text: string }[] {
  const start = lines.findIndex((l) => l.startsWith(`${section}. `));
  if (start < 0) throw new Error(`Rule Manual section ${section} not found`);
  const out: { id: string; text: string }[] = [];
  for (const raw of lines.slice(start + 1)) {
    if (/^\d+(-\d+)?\. /.test(raw)) break;
    const line = raw.replace(/\f/g, "").trim();
    if (!line || /^\d+$/.test(line)) continue;
    const m = /^(\d+(?:-\d+)+)\. (.*)$/.exec(line);
    if (m) out.push({ id: m[1], text: m[2] });
    else if (out.length) out[out.length - 1].text += ` ${line}`;
  }
  return out.map((p) => ({ id: p.id, text: p.text.replace(/\s+/g, " ").trim() }));
}

/** How a card's chip spells the keyword: lower case, no brackets, no placeholder values. */
const spelling = (tag: string) => tag.toLowerCase().replace(/[[\]]/g, "").replace(/\s*:\s*/g, ": ").replace(/(\s+(x|y|xy|\d+))+$/g, "").trim();

export function keywordRulesSource(): string {
  const lines = readFileSync(join(ROOT, "docs/rules/rulemanual.txt"), "utf8").replace(/\f/g, "").split(/\r?\n/);
  const rules = Object.entries(KEYWORDS).map(([name, d]) => ({
    name,
    tag: d.tag,
    spellings: [...new Set([d.tag, ...(d.also ?? [])].map(spelling))],
    section: d.section,
    meaning: d.meaning,
    manual: d.section.split(/,\s*/).flatMap((s) => manualSection(lines, s)),
  }));
  return `// Generated by scripts/emit-keyword-rules.ts from src/lib/arena/glossary.ts and docs/rules/rulemanual.txt. Do not edit.
export interface KeywordRule {
  name: string;
  tag: string;
  /** Lower case, without brackets or placeholder values ("over realm", "awaken: surge"). */
  spellings: string[];
  section: string;
  meaning: string;
  manual: { id: string; text: string }[];
}

export const KEYWORD_RULES: KeywordRule[] = [
${rules.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(KEYWORD_RULES_FILE, keywordRulesSource());
  console.log(`wrote ${KEYWORD_RULES_FILE}`);
}
